"""Glyph art for the Greek font (8 rows per glyph, row 0 = top of the 8x8 cell).
Caps rows 1-6; lowercase x-height rows 3-6 (4 high); ascenders from row 0; descender row 7.
Marks live in rows 0-1 with a blank row 2 above the vowel body.
UP / LO are keyed by Greek letter (the original Latin-key tables are converted at the bottom)."""
def P(*rows):                       # 8 rows, pad to 8
    rows = list(rows)
    assert len(rows) == 8, rows
    return rows

def caps(*r6):  return P('', *r6, '')            # rows 1-6
def low(*r5):   return P('', '', *r5, '')        # rows 2-6 (x-height 5)
def tall(*r7):  return P(*r7, '')                # rows 0-6
def full(*r8):  return P(*r8)                    # rows 0-7

