"""High-Definition Glyph art for the Greek Game Boy Color font (8 rows per glyph).
Caps occupy rows 1-6; lowercase x-height rows 2-6 (5 pixels high); ascenders from row 0/1;
descenders in row 7; diacritics occupy rows 0-1 atop the vowel body.
"""

def P(*rows):
    rows = list(rows)
    assert len(rows) == 8, rows
    return rows

def caps(*r6):  return P('', *r6, '')            # rows 1-6 (height 6)
def low(*r5):   return P('', '', *r5, '')        # rows 2-6 (height 5, standard lowercase body)
def tall(*r7):  return P(*r7, '')                # rows 0-6 (height 7, ascenders)
def low_d(*r6): return P('', '', *r6)            # rows 2-7 (height 6, descenders)
def full(*r8):  return P(*r8)                    # rows 0-7 (full height)

